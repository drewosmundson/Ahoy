  class Node {
    constructor(row, col, height = 1) {
      this.row = row
      this.col = col
      this.height = height
      this.key = `${row}|${col}`
    }

    isValid(){
      let valid = true
            
      valid &= this.height >= 0
      valid &= this.row >= 0
      valid &= this.col >= 1
      valid &= this.row < graph.length
            
      if (valid) {
        valid &= this.col <= graph[this.row]
      }

      return valid
    }

    neighbors() {
      
      const nodes = [] 
      nodes.push(new Node(this.row-1, this.col, this.height - 1))
      nodes.push(new Node(this.row-1, this.col+1, this.height - 1))
      nodes.push(new Node(this.row, this.col-1, this.height - 1.4))
      nodes.push(new Node(this.row, this.col+1, this.height - 1.4))
      nodes.push(new Node(this.row+1, this.col, this.height - 1))
      nodes.push(new Node(this.row+1, this.col+1, this.height - 1))

      return nodes.filter((v) => v.isValid())
    }
  }

  function countConnections(node, length) {
      const closedSet = new Set(node.key)
    const openList = node.neighbors()
    const found = []
    
    let maxDepth = 10000
    while (openList.length > 0 && maxDepth >= 0) {
      maxDepth -= 1
      const nextNode = openList.pop()
      
      if (closedSet.has(nextNode.key)) continue
      closedSet.add(nextNode.key)
      found.push(nextNode)
      
      for (const neighbor of nextNode.neighbors()) {
        openList.push(neighbor)
      }
    }
    

    return found.length 
  }
    
  const depth = 3
  
  const connections = graph.reduce((total, cols, row) => {
       let rowSum = 0
    
    for (let col = 1; col <= cols; col++) {
      rowSum += countConnections(new Node(row, col, depth))
    }
    
    return total + rowSum
  }, 0)
 
  const dps = 62.5
  
  return dps * (total + connections/10) / total * 16
